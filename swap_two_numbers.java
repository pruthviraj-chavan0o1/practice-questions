public class swap_two_numbers {
    public static void main(String[] args){
        int a=10;
        int b=20;

        System.out.println("Before Swapping a=" +a + "and b="+b);

        //swapping 
        //use third variable

        int temp =a;//temp=10
        a=b;//a=20;
        b=temp;//b=10

       
        System.out.println("after Swappint a="+a+"and b="+b);
    }
}
